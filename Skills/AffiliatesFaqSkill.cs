using System.ComponentModel;
using Microsoft.SemanticKernel;

namespace AffiliatesAPI.Skills;

/// <summary>
/// Affiliate Marketing FAQ Skill.
/// Answers questions about the gambling agency's affiliate programme in natural language.
/// No database access — all answers are policy-controlled and served from this layer.
/// </summary>
public class AffiliatesFaqSkill
{
    private readonly ILogger<AffiliatesFaqSkill> _logger;

    public AffiliatesFaqSkill(ILogger<AffiliatesFaqSkill> logger)
    {
        _logger = logger;
    }

    // ─── Kernel Functions ────────────────────────────────────────────────────

    [KernelFunction]
    [Description("Answers frequently asked questions about the affiliate programme, including how to join, commission structures, payment methods, tracking, marketing rules, and general programme policies. Call this for any general affiliate query.")]
    public Task<string> AnswerAffiliateFaq(
        [Description("The affiliate's question about the programme.")] string question)
    {
        _logger.LogInformation("AnswerAffiliateFaq called | Question={Question}", question);

        // ── Commission & Earnings ─────────────────────────────────────────────
        if (Contains(question, "commission", "earn", "revenue share", "cpa", "hybrid", "payout rate", "how much"))
            return Answer("""
                **Commission Structures**

                We offer three flexible commission models:

                1. **Revenue Share (RevShare)** – Earn **25 %–45 %** of the net gaming revenue (NGR) generated by your referred players. The tier you land in depends on the number of active players you bring in each month.

                2. **CPA (Cost Per Acquisition)** – Receive a flat **R 500–R 1 500** for every qualifying first-time depositor (FTD) you refer, depending on the agreed tier and traffic quality.

                3. **Hybrid** – A combination of a reduced CPA upfront plus an on-going RevShare percentage. Great for affiliates who want immediate payouts *and* long-term passive income.

                Contact your dedicated affiliate manager to discuss which model suits your audience best.
                """);

        // ── How to Join ──────────────────────────────────────────────────────
        if (Contains(question, "join", "sign up", "register", "apply", "become an affiliate", "get started", "onboard"))
            return Answer("""
                **How to Join the Affiliate Programme**

                1. Visit our **Affiliate Portal** and click *Register*.
                2. Complete the application — company/individual details, your primary traffic channels, and estimated monthly volume.
                3. Our team reviews applications within **2 business days**.
                4. Once approved you receive your unique tracking links and access to the dashboard.
                5. Start promoting and watch your earnings grow!

                > **Tip:** Applications with a completed media-kit or traffic overview are approved fastest.
                """);

        // ── Payments & Withdrawals ────────────────────────────────────────────
        if (Contains(question, "payment", "withdraw", "pay", "when do i get paid", "payment date", "bank", "transfer", "eft", "crypto"))
            return Answer("""
                **Payments & Withdrawal Information**

                - **Payment cycle:** Commissions are calculated monthly and paid out on or before the **15th of the following month**.
                - **Minimum threshold:** R 500 (or currency equivalent).
                - **Supported methods:** EFT / Bank Transfer, Neteller, Skrill, and USDT (TRC-20 & ERC-20).
                - **Processing time:** EFT — 2–3 business days. E-wallets — 24–48 hours.
                - **Currency:** Payouts in ZAR by default; USD and EUR available on request.

                Ensure your banking details are verified in the portal before the 10th of each month to avoid delays.
                """);

        // ── Tracking & Links ─────────────────────────────────────────────────
        if (Contains(question, "track", "cookie", "link", "pixel", "postback", "referral", "utm", "sub-id"))
            return Answer("""
                **Tracking & Referral Links**

                - We use **first-click attribution** with a **30-day cookie window**.
                - Each affiliate gets unique tracking URLs you can customise with sub-IDs for granular campaign tracking (e.g. `?subid=facebook_ad1`).
                - **Server-side postback (S2S)** integration is available for mobile app affiliates.
                - Real-time statistics are available in your dashboard: clicks, registrations, FTDs, NGR, and commissions — updated every 15 minutes.
                - You can generate campaign-specific links directly from the *Links & Creatives* section of the portal.
                """);

        // ── Marketing Materials ──────────────────────────────────────────────
        if (Contains(question, "banner", "creative", "material", "asset", "logo", "image", "ad", "landing page"))
            return Answer("""
                **Marketing Materials & Creatives**

                A full library of approved creatives is available in the **Creatives** tab of your affiliate dashboard:

                - Static banners in all standard IAB sizes (728×90, 300×250, 160×600, 320×50, etc.)
                - Animated GIF and HTML5 banners
                - Pre-built landing pages optimised for conversion
                - Social media card templates
                - Email templates (compliant with POPIA and CAN-SPAM)

                All materials are updated regularly to reflect active promotions and seasonal campaigns. Only **approved creatives** may be used — using unapproved or altered materials violates our terms.
                """);

        // ── Marketing Rules / What's Allowed ─────────────────────────────────
        if (Contains(question, "rule", "allowed", "prohibited", "spam", "seo", "paid search", "ppc", "brand bid", "terms", "compliance", "what can i"))
            return Answer("""
                **Affiliate Marketing Rules & Compliance**

                ✅ **Allowed:**
                - SEO / organic content and review sites
                - Social media organic content and paid ads (non-brand keywords)
                - Email marketing to your own opted-in list
                - YouTube / streaming / influencer channels
                - Comparison and odds-aggregator sites

                ❌ **Prohibited:**
                - Bidding on our brand keywords or domain in paid search (e.g., Google Ads)
                - Spam (email, SMS, or social)
                - Misleading bonus claims or fake reviews
                - Traffic from jurisdictions where gambling is prohibited
                - Self-referrals or player collusion
                - Incentivised traffic without prior written approval

                Breaching these rules may result in commission forfeiture or account suspension. When in doubt, ask your affiliate manager first.
                """);

        // ── Negative Carryover ────────────────────────────────────────────────
        if (Contains(question, "negative", "carryover", "carry over", "minus", "deficit", "debt"))
            return Answer("""
                **Negative Carryover Policy**

                We operate a **no negative carryover** policy for RevShare affiliates. This means:

                - If a player you referred has an unusually lucky month and your NGR dips below zero, that negative balance is **reset to zero** at the start of the next month.
                - You will never owe us money due to player luck.
                - CPA and Hybrid deals are not affected by player NGR swings — your CPA is locked in once the qualifying conditions are met.
                """);

        // ── Player Referral Exclusivity ───────────────────────────────────────
        if (Contains(question, "exclusive", "shared", "player belong", "who owns the player", "overlap"))
            return Answer("""
                **Player Attribution & Exclusivity**

                - Players are attributed to the **first affiliate** who referred them (first-click, 30-day cookie).
                - Once a player is attributed, they remain tied to that affiliate permanently — even if they return via another affiliate's link later.
                - Players who already have an account prior to clicking your link **cannot** be attributed to you.
                - Sub-affiliate commission sharing is available under our **Multi-Tier** programme — ask your manager for details.
                """);

        // ── Account / Dashboard ──────────────────────────────────────────────
        if (Contains(question, "dashboard", "report", "statistic", "account", "login", "portal", "access"))
            return Answer("""
                **Affiliate Dashboard & Reporting**

                Your dashboard gives you full visibility of your performance:

                - **Real-time stats:** Clicks, Registrations, FTDs, Deposits, NGR, Commissions
                - **Date range filters:** Daily, weekly, monthly, or custom range
                - **Breakdown by:** Campaign, sub-ID, country, and device type
                - **Downloadable reports:** CSV export for all data sets
                - **Invoices & payment history:** Available under *Financials*

                Login at **affiliates.hollywoodbets.net** using the credentials sent to your registered email. Use the *Forgot Password* link if you need to reset.
                """);

        // ── Contact & Support ─────────────────────────────────────────────────
        if (Contains(question, "contact", "support", "help", "manager", "email", "phone", "reach", "talk to someone"))
            return Answer("""
                **Contact Your Affiliate Team**

                | Channel | Details |
                |---------|---------|
                | 📧 Email | affiliates@hollywoodbets.net |
                | 💬 Live Chat | Available in the affiliate portal (Mon–Fri, 08:00–18:00 SAST) |
                | 📞 Phone | +27 31 000 1234 (Business hours) |
                | 🌐 Portal | affiliates.hollywoodbets.net |

                For urgent payment or technical issues, mark your email **[URGENT]** and our team will respond within 4 business hours.
                """);

        // ── Terms & Conditions / Legal ────────────────────────────────────────
        if (Contains(question, "terms", "condition", "agreement", "contract", "legal", "licence", "license", "responsible gambling"))
            return Answer("""
                **Terms, Conditions & Legal**

                - Full **Affiliate Programme Terms & Conditions** are available on the portal under *Legal Docs*.
                - We operate under a valid **National Gambling Board (NGB)** licence and all affiliates must comply with South African gambling advertising standards.
                - Affiliates are required to include **responsible gambling** messaging on all promotional content (we provide compliant copy in the creatives library).
                - Affiliates must not target minors. Any traffic suspected of originating from under-18s will result in immediate account review.
                - The programme terms may be updated with 30 days' notice — you'll be notified via email and the portal.
                """);

        // ── Bonus & Promotions ────────────────────────────────────────────────
        if (Contains(question, "bonus", "promo", "promotion", "welcome offer", "free bet", "offer"))
            return Answer("""
                **Promoting Bonuses & Offers**

                - Our current welcome offer for referred players: **100% matched deposit bonus up to R 1 000** on first deposit.
                - We run seasonal promotions (sports events, jackpots, tournaments) — creatives and copy for these are published in the portal at least **5 days before** the promo goes live.
                - You **may** promote our official bonuses using approved creatives.
                - You **may not** invent bonuses, inflate bonus values, or set wagering requirements that differ from our published terms.
                - Promotions are subject to change — always pull the latest creative from the portal rather than caching old materials.
                """);

        // ── Sub-Affiliates ────────────────────────────────────────────────────
        if (Contains(question, "sub-affiliate", "sub affiliate", "referral chain", "tier", "multi-level", "mlm"))
            return Answer("""
                **Sub-Affiliate Programme**

                Our **two-tier** referral structure lets you earn from affiliates you introduce:

                - Refer another affiliate and earn **5 % of their generated commissions** for the lifetime of their account.
                - Sub-affiliates have their own independent accounts and full dashboard access.
                - There is **no cap** on the number of sub-affiliates you can refer.
                - Sub-affiliate earnings are displayed separately in your dashboard under *Sub-Affiliates*.

                Contact your affiliate manager to activate multi-tier tracking on your account.
                """);

        // ── Fallback ─────────────────────────────────────────────────────────
        return Answer("""
            I don't have a specific answer for that question in my knowledge base right now.

            Here are a few ways I can help you:
            - Ask me about **commissions**, **payments**, **tracking**, **marketing rules**, or **how to join**.
            - Reach your affiliate manager directly at **affiliates@hollywoodbets.net**
            - Chat with support via the portal at **affiliates.hollywoodbets.net**

            I'm happy to answer any other affiliate programme questions!
            """);
    }

    [KernelFunction]
    [Description("Escalates a complex or sensitive affiliate issue (e.g. missing payment, account suspension, compliance dispute) to the affiliate management team. Call this when the user has a specific account issue that cannot be resolved with a general FAQ answer.")]
    public Task<string> EscalateAffiliateIssue(
        [Description("A brief description of the affiliate's issue.")] string issueDescription,
        [Description("Optional: The affiliate's registered email or username.")] string? affiliateId = null)
    {
        _logger.LogInformation(
            "EscalateAffiliateIssue called | Issue={Issue} AffiliateId={Id}",
            issueDescription, affiliateId);

        var idNote = string.IsNullOrWhiteSpace(affiliateId)
            ? "Please include your registered email or username when you follow up."
            : $"Reference ID on file: **{affiliateId}**";

        return Task.FromResult($"""
            ✅ Your issue has been escalated to our affiliate management team.

            {idNote}

            **What happens next:**
            - A team member will review your case and reach out within **5 business hours**.
            - For urgent matters you can also email **affiliates@hollywoodbets.net** with the subject line **[ESCALATION]**.

            Thank you for your patience — we're committed to resolving this as quickly as possible.
            """);
    }

    // ─── Private Helper ───────────────────────────────────────────────────────

    private static bool Contains(string text, params string[] keywords)
        => keywords.Any(k => text.Contains(k, StringComparison.OrdinalIgnoreCase));

    private static Task<string> Answer(string text) => Task.FromResult(text.Trim());
}
